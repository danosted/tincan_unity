<#
.SYNOPSIS
  Writes .docs/plans/README.md, the index of every plan grouped by status, from each plan's first line and title.

.DESCRIPTION
  Every plan in .docs/plans/ starts with a line "Status: <Draft|Approved|Done> <detail>" and has one
  "# Title" heading. The index lists each plan once under its status, with its title and the rest of its status line.
  A plan without a valid first line stops the script (exit 1) and nothing is written.
  -Check writes nothing: exit 0 when the index is up to date, 1 when it is stale or a plan has no valid status.
  Rule: AGENTS.md, "Project quick facts".

.EXAMPLE
  .\.tools\plans.ps1          # regenerate the index after adding a plan or changing a status
  .\.tools\plans.ps1 -Check   # is the index up to date?
#>
param(
    [switch]$Check
)

$ErrorActionPreference = "Stop"

$PlansDir = Join-Path (Split-Path $PSScriptRoot -Parent) ".docs/plans"
$IndexPath = Join-Path $PlansDir "README.md"
# Active work first, the record last.
$Statuses = "Approved", "Draft", "Done"

$plans = @()
$problems = @()
foreach ($file in Get-ChildItem $PlansDir -Filter *.md | Where-Object Name -ne "README.md" | Sort-Object Name) {
    $lines = Get-Content $file.FullName
    $title = ($lines | Where-Object { $_ -match '^# ' } | Select-Object -First 1) -replace '^# ', ''
    if ($lines.Count -eq 0 -or $lines[0] -notmatch '^Status: (\w+)\s*(.*)$' -or $Matches[1] -notin $Statuses) {
        $problems += "$($file.Name): the first line must be 'Status: $($Statuses -join ' | ') ...'"
        continue
    }
    if (-not $title) {
        $problems += "$($file.Name): no '# Title' heading"
        continue
    }
    $plans += [pscustomobject]@{ File = $file.Name; Status = $Matches[1]; Detail = $Matches[2] -replace '^[;:,.]\s*', ''; Title = $title }
}

if ($problems) {
    $problems | ForEach-Object { Write-Host $_ -ForegroundColor Red }
    exit 1
}

$out = @(
    "# Plans"
    ""
    "Every plan, grouped by its first line (``Status: ...``). Generated by ``.tools/plans.ps1``: do not edit by hand;"
    "change the plan's status line, then run ``.\.tools\plans.ps1``."
)
foreach ($status in $Statuses) {
    $group = @($plans | Where-Object Status -eq $status)
    if ($group.Count -eq 0) { continue }
    $out += "", "## $status ($($group.Count))", ""
    foreach ($plan in $group) {
        $row = "- [$($plan.Title)]($($plan.File))"
        if ($plan.Detail) { $row += " — $($plan.Detail)" }
        $out += $row
    }
}
$text = ($out -join "`n") + "`n"

$current = if (Test-Path $IndexPath) { [IO.File]::ReadAllText($IndexPath) -replace "`r`n", "`n" } else { "" }
if ($Check) {
    if ($current -eq $text) { Write-Host "Plan index is up to date."; exit 0 }
    Write-Host "Plan index is stale: run .\.tools\plans.ps1" -ForegroundColor Red
    exit 1
}
[IO.File]::WriteAllText($IndexPath, $text, [Text.UTF8Encoding]::new($false))
Write-Host "Wrote $IndexPath ($($plans.Count) plans)."
